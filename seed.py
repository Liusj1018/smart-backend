async def clear_existing_data(session: AsyncSession) -> None:
    """Delete all existing data in dependency order (child tables first)."""
    print("  Clearing existing data...")
    await session.execute(delete(AuditLog))
    await session.execute(delete(Commit))
    await session.execute(delete(RepoMember))
    await session.execute(delete(TeamMember))
    await session.execute(delete(Repo))
    await session.execute(delete(User))
    await session.execute(delete(Team))
    await session.flush()
    print("  All existing data cleared.")


