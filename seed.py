def _password_hash() -> str:
    """Generate a bcrypt password hash for seeded users.

    Uses a known password ("password123") so that any seeded Faker
    user can log in during development.  The hash is a proper bcrypt
    hash compatible with ``app.core.security.verify_password``.
    """
    return hash_password("password123")


def _generate_sha(seed_str: str) -> str:
    """Generate a deterministic 40-char SHA from a seed string."""
    return hashlib.sha1(seed_str.encode()).hexdigest()


def _random_commit_message() -> str:
    """Generate a random conventional-commit style message."""
    ctype = fake.random_element(COMMIT_TYPES)
    scope = fake.random_element(COMMIT_SCOPES)
    subject = fake.random_element(COMMIT_SUBJECTS)
    return f"{ctype}({scope}): {subject}"


def _slugify(name: str) -> str:
    """Create a URL-friendly slug from a name."""
    return name.lower().replace(" ", "-").replace(".", "")


