"""Idempotent database seed script for development.

Populates the database with Faker-generated sample data:
- 5 teams (>= 3 required)
- 5-10 members per team (random, within 5-10 range)
- 2-3 repos per team
- 3-5 commits per developer (random, within 3-5 range)
- 2-4 audit logs per team

All data is generated by Faker — no real user information is used.

Usage:
    python seed.py

The script is idempotent — it first deletes existing seed data in
dependency order, then inserts fresh data.
"""

import asyncio
import hashlib
import sys
from datetime import UTC, datetime, timedelta
from uuid import uuid4

from faker import Faker
from sqlalchemy import delete
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.security import hash_password
from app.db.models.audit_log import AuditLog
from app.db.models.commit import Commit
from app.db.models.repo import Repo
from app.db.models.repo_member import RepoMember
from app.db.models.team import Team
from app.db.models.team_member import TeamMember
from app.db.models.user import User
from app.db.session import AsyncSessionLocal, engine

fake = Faker()
Faker.seed(42)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

NUM_TEAMS = 5
MIN_MEMBERS_PER_TEAM = 5
MAX_MEMBERS_PER_TEAM = 10
MIN_REPOS_PER_TEAM = 2
MAX_REPOS_PER_TEAM = 3
MIN_COMMITS_PER_DEVELOPER = 3
MAX_COMMITS_PER_DEVELOPER = 5
MIN_AUDIT_LOGS_PER_TEAM = 2
MAX_AUDIT_LOGS_PER_TEAM = 4

ROLES = ["admin", "developer", "developer", "developer", "viewer"]

COMMIT_TYPES = ["feat", "fix", "refactor", "docs", "test", "chore", "perf", "style"]
COMMIT_SCOPES = [
    "auth",
    "api",
    "db",
    "ui",
    "config",
    "middleware",
    "models",
    "routes",
    "services",
    "utils",
]
COMMIT_SUBJECTS = [
    "add new endpoint",
    "resolve null pointer issue",
    "simplify session handling",
    "update documentation",
    "add integration tests",
    "upgrade dependencies",
    "optimize query performance",
    "format code",
    "correct timezone handling",
    "implement middleware",
    "refactor service layer",
    "fix validation logic",
    "add caching layer",
    "improve error messages",
    "add input sanitization",
]

AUDIT_ACTIONS = [
    ("member.invited", "member"),
    ("repo.created", "repo"),
    ("commit.imported", "commit"),
    ("member.role_updated", "member"),
    ("repo.updated", "repo"),
    ("member.removed", "member"),
    ("team.settings_updated", "team"),
    ("repo.deleted", "repo"),
]


